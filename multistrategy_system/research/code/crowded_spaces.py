RESULTS_DIR = ts.RESULTS_DIR
HOLD_FILE = os.path.join(RESULTS_DIR, 'inst_holdings_sp500.csv.gz')
LAG_DAYS = 46
START, END = '2020-05-01', '2026-08-31'
sr, monthly = ts.sr, ts.monthly


def anomaly_signals(px, uni, chg, sec, fin, sp, spy):
    """Month-end panel with the six anomaly signals (signed: high = long), ISS/SI from the
    Taking Sides builder, SEAS from the seasonality builder, MOM/REV/IVOL from prices."""
    base = ts.build_signals(px, sp, uni, chg, sec, fin)               # ISS (signed high=long), SHT, mcap
    seas = se.build_signals(px, uni, chg, sec, sp)[['date', 'symbol', 'SEAS']]
    fin = fin[fin.symbolCode.isin(uni)].copy()
    fin['si'] = pd.to_numeric(fin.currentShortPositionQuantity, errors='coerce')
    fin['adv'] = pd.to_numeric(fin.averageDailyVolumeQuantity, errors='coerce')
    fin['avail'] = fin.settlementDate + pd.Timedelta(days=ts.FINRA_LAG_DAYS)
    si_by = {k: v.sort_values('settlementDate') for k, v in fin.groupby('symbolCode')}
    shares = shares_asof(sec)
    sh_by = {k: v.set_index('filed')['val'].sort_index() for k, v in shares[shares.symbol.isin(uni)].groupby('symbol')}
    rets = px.pct_change(fill_method=None)
    rows = []
    for d, g in base.groupby('date'):
        p_now = px.loc[:d].iloc[-1]
        p_1m = px.loc[:d - pd.DateOffset(months=1)].iloc[-1]
        p_12m = px.loc[:d - pd.DateOffset(months=12)].iloc[-1]
        r60 = rets.loc[:d].tail(60)
        s60 = spy.reindex(r60.index)
        for s in g.symbol:
            mom = rev = ivol = si = adv = np.nan
            if s in px.columns:
                if pd.notna(p_12m.get(s)) and pd.notna(p_1m.get(s)) and p_12m[s] > 0 and p_1m[s] > 0:
                    mom = p_1m[s] / p_12m[s] - 1.0                      # 12-1
                    rev = -(p_now[s] / p_1m[s] - 1.0)                   # long low prior-month return
                x = r60[s]
                if x.notna().sum() >= 40:
                    j = pd.concat([x, s60], axis=1).dropna()
                    b = j.iloc[:, 0].cov(j.iloc[:, 1]) / j.iloc[:, 1].var()
                    ivol = -float((j.iloc[:, 0] - b * j.iloc[:, 1]).std())   # long low ivol
            q = si_by.get(s)
            if q is not None:
                av = q[q.avail <= d]
                if len(av):
                    t1 = av.iloc[-1]
                    sh = sh_by.get(s)
                    adv = t1.adv
                    if sh is not None and len(sh.loc[:d]):
                        so = sh.loc[:d].iloc[-1] * ts.split_factor_to_now(sp, s, sh.loc[:d].index[-1])
                        sis = t1.si * ts.split_factor_to_now(sp, s, t1.settlementDate)
                        if so > 0:
                            si = -(sis / so)                                 # long low short interest
            rows.append({'date': d, 'symbol': s, 'MOM': mom, 'REV': rev, 'IVOL': ivol, 'SI': si, 'adv': adv})
    panel = base[['date', 'symbol', 'ISS', 'mcap']].merge(pd.DataFrame(rows), on=['date', 'symbol'], how='left')
    panel = panel.merge(seas, on=['date', 'symbol'], how='left')
    return panel


def attach_crowding(panel, hold, sec, sp, uni):
    """DTL and IO at each month-end from the latest quarter whose holdings are available."""
    hold = hold.copy()
    hold['avail'] = hold.period + pd.Timedelta(days=LAG_DAYS)
    hb = {k: v.sort_values('period') for k, v in hold.groupby('symbol')}
    shares = shares_asof(sec)
    sh_by = {k: v.set_index('filed')['val'].sort_index() for k, v in shares[shares.symbol.isin(uni)].groupby('symbol')}
    dtl, io_, nm = [], [], []
    for r in panel.itertuples():
        h = hb.get(r.symbol)
        v = np.nan; io = np.nan; n = np.nan
        if h is not None:
            a = h[h.avail <= r.date]
            if len(a):
                last = a.iloc[-1]
                n = last.n_managers
                if pd.notna(r.adv) and r.adv > 0:
                    v = last.inst_shares / r.adv
                sh = sh_by.get(r.symbol)
                if sh is not None and len(sh.loc[:r.date]):
                    so = sh.loc[:r.date].iloc[-1] * ts.split_factor_to_now(sp, r.symbol, sh.loc[:r.date].index[-1])
                    # holdings are in the share basis of the quarter end; adjust to now
                    hs = last.inst_shares * ts.split_factor_to_now(sp, r.symbol, last.period)
                    if so > 0:
                        io = hs / so
        dtl.append(v); io_.append(io); nm.append(n)
    panel['DTL'], panel['IO'], panel['NMGR'] = dtl, io_, nm
    return panel


ANOMS = ['MOM', 'REV', 'IVOL', 'ISS', 'SI', 'SEAS']


def legs(g, anoms):
    top = pd.DataFrame({a: g[a].rank(pct=True) > 0.8 for a in anoms})
    bot = pd.DataFrame({a: g[a].rank(pct=True) <= 0.2 for a in anoms})
    long = top.any(axis=1) & ~bot.any(axis=1)
    short = bot.any(axis=1) & ~top.any(axis=1)
    return long.values, short.values


def weights_for(g, mode, crowd='DTL', anoms=ANOMS):
    L, S = legs(g, anoms)
    gl, gs = g[L].dropna(subset=[crowd]), g[S].dropna(subset=[crowd])
    if mode == 'ALL':
        pass
    elif mode == 'CS':
        gl = gl[gl[crowd].rank(pct=True) > 2 / 3]
        gs = gs[gs[crowd].rank(pct=True) <= 1 / 3]
    elif mode == 'REV_CS':
        gl = gl[gl[crowd].rank(pct=True) <= 1 / 3]
        gs = gs[gs[crowd].rank(pct=True) > 2 / 3]
    if len(gl) < 10 or len(gs) < 10:
        return None
    return pd.concat([pd.Series(1.0 / len(gl), index=gl.symbol), pd.Series(-1.0 / len(gs), index=gs.symbol)])


def run(panel, px, mode, cost_bps=10.0, crowd='DTL', anoms=ANOMS):
    rets = px.pct_change(fill_method=None)
    dates = sorted(panel.date.unique())
    w_prev = pd.Series(dtype=float)
    daily, turn = [], {}
    for i, d in enumerate(dates):
        g = panel[panel.date == d]
        w = weights_for(g, mode, crowd, anoms)
        if w is None:
            continue
        w = w.groupby(level=0).sum()
        turn[d] = w.subtract(w_prev, fill_value=0.0).abs().sum()
        w_prev = w
        nxt = dates[i + 1] if i + 1 < len(dates) else px.index[-1]
        r = rets.loc[d + pd.Timedelta(days=1):nxt, w.index].fillna(0.0)
        cum = (1 + r).cumprod()
        pv = pd.concat([pd.Series([w.sum()], index=[d]), (cum * w).sum(axis=1)])
        dr = pv.diff().iloc[1:]
        dr.iloc[0] -= turn[d] * cost_bps / 1e4
        daily.append(dr)
    out = pd.concat(daily).sort_index()
    return out[~out.index.duplicated()].loc[START:END], pd.Series(turn)


def main():
    px = pd.read_csv(se.PX_LONG, index_col=0, parse_dates=True).sort_index()
    uni = pd.read_csv(ts.UNI_FILE).iloc[:, 0].astype(str).tolist()
    chg = pd.read_csv(ts.CHG_FILE, parse_dates=['date'])
    sec = pd.read_csv(ts.SEC_FILE)
    fin = pd.read_csv(ts.FINRA_FILE, parse_dates=['settlementDate'])
    sp = pd.read_csv(os.path.join(ts.BD, 'sp500_splits_detected.csv'), parse_dates=['date', 'window_start'])
    hold = pd.read_csv(HOLD_FILE, parse_dates=['period', 'filed_first', 'filed_median', 'filed_last'])
    spy = t2.load_prices()['SPY'].pct_change(fill_method=None)
    print(f"Holdings: {hold.symbol.nunique()} symbols, quarters {hold.period.min().date()}..{hold.period.max().date()}; "
          f"median managers per stock {hold.n_managers.median():.0f}; median filing lag to last filer "
          f"{(hold.filed_last - hold.period).dt.days.median():.0f} days, to median filer {(hold.filed_median - hold.period).dt.days.median():.0f}")
    panel_file = os.path.join(RESULTS_DIR, 'crowded_spaces_panel.csv')
    if os.path.exists(panel_file):
        panel = pd.read_csv(panel_file, parse_dates=['date'])
    else:
        panel = anomaly_signals(px, uni, chg, sec, fin, sp, spy)
        panel = attach_crowding(panel, hold, sec, sp, uni)
        panel.to_csv(panel_file, index=False)
    cov = panel.groupby('date').agg(n=('symbol', 'size'), dtl=('DTL', 'count'), **{a: (a, 'count') for a in ANOMS})
    print(f"Panel: {len(cov)} month-ends, names/month median {cov.n.median():.0f}, with DTL {cov.dtl.median():.0f}; "
          + ", ".join(f"{a} {cov[a].median():.0f}" for a in ANOMS))
    print(f"DTL median {panel.DTL.median():.1f} days, IO median {panel.IO.median():.2f}; corr(DTL, IO) {panel.DTL.corr(panel.IO):+.2f}; "
          f"corr(DTL, log mcap) {panel.DTL.corr(np.log(panel.mcap)):+.2f}")

    series = {}
    print(f"\n{'portfolio':22s}{'net SR':>8s}{'5bp':>7s}{'20bp':>7s}{'ann':>8s}{'vol':>7s}{'MDD':>8s}{'beta':>7s}{'last2y':>8s}{'TO/mo':>7s}{'n L/S':>10s}")
    def report(label, mode, crowd='DTL', anoms=ANOMS):
        r, to = run(panel, px, mode, 10.0, crowd, anoms)
        r5, r20 = run(panel, px, mode, 5.0, crowd, anoms)[0], run(panel, px, mode, 20.0, crowd, anoms)[0]
        m = monthly(r)
        j = pd.concat([m.rename('r'), monthly(spy.reindex(r.index)).rename('s')], axis=1).dropna()
        beta = j['r'].cov(j['s']) / j['s'].var()
        g = panel[panel.date == sorted(panel.date.unique())[-1]]
        w = weights_for(g, mode, crowd, anoms)
        nls = f"{(w > 0).sum()}/{(w < 0).sum()}" if w is not None else 'n/a'
        series[label] = r
        print(f"{label:22s}{sr(m):8.2f}{sr(monthly(r5)):7.2f}{sr(monthly(r20)):7.2f}{r.mean() * 252:8.1%}{r.std() * np.sqrt(252):7.1%}"
              f"{bb.maxdd(r):8.1%}{beta:7.2f}{sr(monthly(r.loc['2024-09-01':])):8.2f}{to.mean():7.2f}{nls:>10s}")
        return r
    cs = report('CS (paper)', 'CS')
    allr = report('ALL (control)', 'ALL')
    report('REV_CS (mirror)', 'REV_CS')
    report('CS by IO', 'CS', crowd='IO')
    for a in ANOMS:
        report(f'CS {a} only', 'CS', anoms=[a])
        report(f'ALL {a} only', 'ALL', anoms=[a])
    m = monthly(cs)
    print("Per-year net Sharpe CS: " + "  ".join(f"{y}:{sr(x):+.2f}" for y, x in m.groupby(m.index.year)))
    print("Per-year net Sharpe ALL: " + "  ".join(f"{y}:{sr(x):+.2f}" for y, x in monthly(allr).groupby(monthly(allr).index.year)))

    c1 = (sr(m) >= 0.50) and (sr(m) - sr(monthly(allr)) >= 0.20)
    c2 = sr(m.loc['2024-09-01':]) > 0
    tot = (1 + m).prod() - 1
    blocks = {str(a.date()): (1 + m.loc[a:a + pd.DateOffset(months=23)]).prod() - 1 for a in m.index[:-23]}
    conc = max(blocks.values()) / tot if tot > 0 else np.inf
    c3 = conc <= 0.75
    eq, tr = bb.load_equity(), bb.load_trend()
    full = pd.concat([eq, tr, cs.rename('cs')], axis=1)
    bb.FULL_FRAME = full
    j = full.loc['2020-01-01':'2025-12-31'].dropna()
    jm = j.resample('ME').sum()
    c_eq, c_tr = jm['cs'].corr(jm['equity']), jm['cs'].corr(jm['trend'])
    js = pd.concat([m.rename('r'), monthly(spy.reindex(cs.index)).rename('s')], axis=1).dropna()
    beta = js['r'].cov(js['s']) / js['s'].var()
    book2 = bb.book_returns(j[['equity', 'trend']], 'WF')
    b2m = monthly(book2)
    bad = jm.loc[b2m[b2m <= b2m.quantile(0.2)].index, 'cs']
    c4 = (c_eq < 0.10) and (c_tr < 0.10) and (abs(beta) < 0.25) and (bad.mean() > 0)
    book3 = bb.book_returns(j[['equity', 'trend', 'cs']], 'WF')
    y2, y3 = bb.yearly(book2), bb.yearly(book3)
    c5 = (bb.sharpe(book3) >= bb.sharpe(book2)) and (min(y3.values()) >= min(y2.values())) and (bb.maxdd(book3) >= bb.maxdd(book2))
    print("\nGO/NO-GO (pre-registered, CS):")
    print(f"  {'PASS' if c1 else 'fail'}  C1 CS net Sharpe {sr(m):.2f} (>= 0.50); CS - ALL = {sr(m) - sr(monthly(allr)):+.2f} (>= 0.20)")
    print(f"  {'PASS' if c2 else 'fail'}  C2 last two years {sr(m.loc['2024-09-01':]):+.2f} (> 0)")
    print(f"  {'PASS' if c3 else 'fail'}  C3 best 24-month block = {conc:.0%} of profit (<= 75%)")
    print(f"  {'PASS' if c4 else 'fail'}  C4 corr equity {c_eq:+.2f}, trend {c_tr:+.2f}; beta {beta:+.2f}; bad-month mean {bad.mean() * 100:+.2f}% (n={len(bad)}, hit {(bad > 0).mean():.0%})")
    print(f"  {'PASS' if c5 else 'fail'}  C5 WF book rf {bb.sharpe(book2):.2f} -> {bb.sharpe(book3):.2f}; worst {min(y2.values()):+.2f} -> {min(y3.values()):+.2f}; MDD {bb.maxdd(book2):.1%} -> {bb.maxdd(book3):.1%}")
    print(f"  info  book no-rf {bb.sharpe(book2, 0):.2f} -> {bb.sharpe(book3, 0):.2f}")
    print(f"\nVERDICT: {'PROMOTE to paper-sleeve candidate' if all([c1, c2, c3, c4, c5]) else 'not promoted'}")
    pd.DataFrame(series).to_csv(os.path.join(RESULTS_DIR, 'crowded_spaces_daily.csv'))
    print("Saved results/crowded_spaces_panel.csv, crowded_spaces_daily.csv")


if __name__ == '__main__':
    main()

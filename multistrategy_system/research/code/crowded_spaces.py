"""
Crowded Spaces — RESEARCH ONLY. Gate pre-registered 2026-09-16 before any return was computed.

Source: Lazo-Paz, Moneta & Chincarini, "Crowded Spaces and Anomalies", J. Banking & Finance 182
(2026), SSRN 2023. Abstract (Crossref, verbatim): "anomaly risk-adjusted returns are primarily
generated by the most (least) crowded stocks for the long-leg (short-leg) portfolio ... our
results remain significant after publication dates ... crowded equity positions in anomaly
stocks increase institutional investors' exposure to crash risk." Note this is the OPPOSITE of
the 2026-09-02 scan's summary ("long uncrowded / short crowded"), corrected here from the
abstract. Their sample: 1980-2021. Ours: 2020-05..2026-08, the part after their sample plus
2020-21 overlap, on S&P 500 names.

Crowding (stock level, our proxy for the paper's days-to-liquidate): institutional days to
liquidate DTL = aggregate 13F shares held (original 13F-HR filings, share positions only) /
FINRA average daily volume; holdings for quarter-end q are used from the first month-end at
least 46 days after q (the 45-day filing deadline). Institutional ownership share IO =
13F shares / shares outstanding is informational.

Anomaly legs (each signed so that the long leg is the high-expected-return side; quintiles
within the dated S&P 500 universe at each month-end):
  MOM   12-1 momentum (long high)         REV   1-month reversal (long low prior-month return)
  IVOL  60-day idiosyncratic vol vs SPY (long low)
  ISS   12-month net issuance (long low)   SI    short interest / shares (long low)
  SEAS  20-year same-month mean (long high)
A stock is in the pooled long leg if it is in the top quintile of at least one anomaly and in
no bottom quintile; pooled short leg the mirror. Crowding tercile is computed within each leg.

Portfolios (equal-weight, monthly, 10 bp per unit of one-way turnover; 5 and 20 reported):
  CS    the paper's claim: long the MOST crowded tercile of the pooled long leg, short the
        LEAST crowded tercile of the pooled short leg.
  ALL   control: the whole pooled long leg vs the whole pooled short leg.
  REV_CS the mirror (long least-crowded longs, short most-crowded shorts), informational.
  Per-anomaly CS versions, informational.

Pre-registered gate (CS, EW; net Sharpe = no-rf, monthly*sqrt(12)):
  C1 alpha: CS net Sharpe >= 0.50 at 10 bp AND CS - ALL >= 0.20 (the filter must add, not
     just ride the anomalies).                                                        binding
  C2 recency: 2024-09..latest > 0.                                                    binding
  C3 concentration: no 24-month block > 75% of profit.                                binding
  C4 orthogonality: monthly corr with equity and trend < 0.10; |beta| < 0.25; mean > 0 in
     the WF equity+trend book's worst-quintile months.                                binding
  C5 book: WF inverse-vol equity+trend+CS not worse on rf-Sharpe, worst year, MaxDD.   binding
  Informational: ALL, REV_CS, per-anomaly CS, IO-based crowding, 5/20 bp, per year.
Decision: C1-C5 pass -> paper-sleeve candidate. Any fail -> not.
Trials: T-2026-09-16-35 (CS), -36 (ALL control), -37 (REV_CS mirror).
Usage: /usr/local/bin/python3 crowded_spaces.py
"""

